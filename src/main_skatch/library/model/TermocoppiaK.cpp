const int TermocoppiaK::tableSize = sizeof(calibrationTable) / sizeof(CalibrationPoint);

TermocoppiaK::TermocoppiaK() {
    Serial.println("[TermocoppiaK] Inizializzata con " + String(tableSize) + " punti di calibrazione (0-1300°C)");
}

TermocoppiaK::~TermocoppiaK() {
    Serial.println("[TermocoppiaK] Distruttore chiamato");
}

float TermocoppiaK::getTemperature(float millivolts) {
    Serial.print("[TermocoppiaK] Input: ");
    Serial.print(millivolts, 3);
    Serial.println(" mV");
    
    // Valida il range di tensione
    if (!isValidVoltage(millivolts)) {
        Serial.print("[TermocoppiaK] ERRORE: Tensione fuori range: ");
        Serial.print(millivolts, 3);
        Serial.println(" mV");
        return ERROR_VALUE;
    }
    
    float temperature = interpolate(millivolts);
    
    Serial.print("[TermocoppiaK] Temperatura finale: ");
    Serial.print(temperature, 2);
    Serial.println(" °C");
    
    return temperature;
}

bool TermocoppiaK::isValidVoltage(float millivolts) const {
    return (millivolts >= calibrationTable[0].voltage && 
            millivolts <= calibrationTable[tableSize - 1].voltage);
}

float TermocoppiaK::interpolate(float voltage) const {
    // Cerca i due punti più vicini nella tabella per l'interpolazione
    for (int i = 0; i < tableSize - 1; i++) {
        if (voltage >= calibrationTable[i].voltage && voltage <= calibrationTable[i + 1].voltage) {
            // Interpolazione lineare tra i due punti
            float x0 = calibrationTable[i].voltage;
            float y0 = calibrationTable[i].temperature;
            float x1 = calibrationTable[i + 1].voltage;
            float y1 = calibrationTable[i + 1].temperature;
            
            // Formula di interpolazione lineare: y = y0 + (x - x0) * (y1 - y0) / (x1 - x0)
            float temperature = y0 + (voltage - x0) * (y1 - y0) / (x1 - x0);
            
            Serial.print("[TermocoppiaK] Interpolazione: ");
            Serial.print(voltage, 3);
            Serial.print(" mV tra [");
            Serial.print(y0, 1);
            Serial.print("°C @ ");
            Serial.print(x0, 3);
            Serial.print(" mV] e [");
            Serial.print(y1, 1);
            Serial.print("°C @ ");
            Serial.print(x1, 3);
            Serial.print(" mV] = ");
            Serial.print(temperature, 2);
            Serial.println("°C");
            
            return temperature;
        }
    }
    
    // Se arriviamo qui, c'è un errore nella logica
    Serial.println("[TermocoppiaK] ERRORE: Impossibile interpolare il valore");
    return ERROR_VALUE;
}
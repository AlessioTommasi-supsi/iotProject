const int PT1000::tableSize = sizeof(calibrationTable) / sizeof(CalibrationPoint);

PT1000::PT1000() {
    Serial.println("[PT1000] Inizializzata con " + String(tableSize) + " punti di calibrazione IEC 751 (-80°C a +300°C)");
}

PT1000::~PT1000() {
    Serial.println("[PT1000] Distruttore chiamato");
}

float PT1000::getTemperature(float resistance) {
    Serial.print("[PT1000] Input resistenza: ");
    Serial.print(resistance, 2);
    Serial.println(" Ohm");
    
    // Valida il range di resistenza
    if (!isValidResistance(resistance)) {
        Serial.print("[PT1000] ERRORE: Resistenza fuori range: ");
        Serial.print(resistance, 2);
        Serial.print(" Ohm (range: ");
        Serial.print(MIN_RESISTANCE, 2);
        Serial.print(" - ");
        Serial.print(MAX_RESISTANCE, 2);
        Serial.println(" Ohm)");
        return ERROR_VALUE;
    }
    
    float temperature = interpolate(resistance);
    
    Serial.print("[PT1000] Temperatura finale: ");
    Serial.print(temperature, 2);
    Serial.println(" °C");
    
    return temperature;
}

bool PT1000::isValidResistance(float resistance) const {
    return (resistance >= MIN_RESISTANCE && resistance <= MAX_RESISTANCE);
}

float PT1000::interpolate(float resistance) const {
    // Cerca i due punti più vicini nella tabella per l'interpolazione
    for (int i = 0; i < tableSize - 1; i++) {
        if (resistance >= calibrationTable[i].resistance && resistance <= calibrationTable[i + 1].resistance) {
            // Interpolazione lineare tra i due punti
            float x0 = calibrationTable[i].resistance;
            float y0 = calibrationTable[i].temperature;
            float x1 = calibrationTable[i + 1].resistance;
            float y1 = calibrationTable[i + 1].temperature;
            
            // Formula di interpolazione lineare: y = y0 + (x - x0) * (y1 - y0) / (x1 - x0)
            float temperature = y0 + (resistance - x0) * (y1 - y0) / (x1 - x0);
            
            Serial.print("[PT1000] Interpolazione: ");
            Serial.print(resistance, 2);
            Serial.print(" Ohm tra [");
            Serial.print(y0, 1);
            Serial.print("°C @ ");
            Serial.print(x0, 2);
            Serial.print(" Ohm] e [");
            Serial.print(y1, 1);
            Serial.print("°C @ ");
            Serial.print(x1, 2);
            Serial.print(" Ohm] = ");
            Serial.print(temperature, 2);
            Serial.println("°C");
            
            return temperature;
        }
    }
    
    // Se arriviamo qui, c'è un errore nella logica
    Serial.println("[PT1000] ERRORE: Impossibile interpolare il valore");
    return ERROR_VALUE;
}